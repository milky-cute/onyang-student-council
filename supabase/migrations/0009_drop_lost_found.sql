-- -----------------------------------------------------------------------------
-- 1. 테이블 삭제
--
-- 테이블에 붙은 RLS 정책(누구나 조회/등록, 임원만 수정/삭제)은 테이블과 함께
-- 자동으로 사라지므로 따로 지우지 않는다.
-- -----------------------------------------------------------------------------
drop table if exists public.lost_found_items;


-- -----------------------------------------------------------------------------
-- 2. storage.objects 에 걸어둔 lost-found 정책 삭제
--
-- storage.objects 는 다른 버킷(media)과 공유하는 테이블이라 버킷을 지워도
-- 정책은 남는다. 0008 에서 만든 정책은 이름이 전부 'lost-found ' 로 시작한다.
-- media 정책은 이 패턴에 걸리지 않으므로 영향을 받지 않는다.
-- -----------------------------------------------------------------------------
do $$
declare
  r record;
begin
  for r in
    select policyname
    from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname like 'lost-found %'
  loop
    execute format('drop policy %I on storage.objects', r.policyname);
  end loop;
end
$$;


-- -----------------------------------------------------------------------------
-- 3. 버킷에 남아있는 오브젝트(업로드된 사진) 삭제
--
-- storage.objects.bucket_id 가 storage.buckets 를 참조하므로 오브젝트를 먼저
-- 지워야 버킷을 지울 수 있다.
-- -----------------------------------------------------------------------------
delete from storage.objects
where bucket_id = 'lost-found';


-- -----------------------------------------------------------------------------
-- 4. 버킷 삭제
-- -----------------------------------------------------------------------------
delete from storage.buckets
where id = 'lost-found';
